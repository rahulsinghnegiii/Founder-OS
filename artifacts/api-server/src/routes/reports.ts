import { Router } from "express";
import { toJson } from "../lib/serialize";
import { eq, desc } from "drizzle-orm";
import { db, reportsTable } from "@workspace/db";
import {
  ListReportsResponse,
  ListReportsQueryParams,
  GetReportParams,
  GetReportResponse,
  GenerateReportBody,
} from "@workspace/api-zod";

const router = Router();

const REPORT_TEMPLATES: Record<string, (data: unknown) => string> = {
  daily_briefing: () => `## Daily Briefing\n\n**Date:** ${new Date().toLocaleDateString()}\n\n### Summary\nOperational overview generated by FounderOS. All systems nominal.\n\n### Top Priorities\n- Review pipeline opportunities\n- Follow up on pending proposals\n- Check project milestone status\n\n### Alerts\n- 2 tasks approaching deadline\n- 1 lead needs follow-up\n\n### Recommendations\n- Schedule time to review Q2 strategy\n- Update lead scoring for qualified pipeline`,
  revenue: () => `## Revenue Report\n\n**Generated:** ${new Date().toLocaleDateString()}\n\n### Summary\nRevenue analysis across all active deals and subscriptions.\n\n### Metrics\n- Total received: tracked in dashboard\n- Pipeline value: sum of qualified leads\n- Projected: based on probability scores`,
  operational: () => `## Operational Report\n\n**Generated:** ${new Date().toLocaleDateString()}\n\n### Department Status\nAll departments operational. Agents performing within expected parameters.\n\n### Workflow Execution\nAutomation workflows running normally.\n\n### Bottlenecks Identified\n- Review pending tasks queue\n- Clear notification backlog`,
};

router.get("/reports", async (req, res): Promise<void> => {
  const query = ListReportsQueryParams.safeParse(req.query);
  let rows;
  if (query.success && query.data.type) {
    rows = await db.select().from(reportsTable).where(eq(reportsTable.type, query.data.type)).orderBy(desc(reportsTable.createdAt));
  } else {
    rows = await db.select().from(reportsTable).orderBy(desc(reportsTable.createdAt));
  }
  res.json(ListReportsResponse.parse(toJson(rows)));
});

router.post("/reports", async (req, res): Promise<void> => {
  const parsed = GenerateReportBody.safeParse(req.body);
  if (!parsed.success) { res.status(400).json({ error: parsed.error.message }); return; }
  const content = REPORT_TEMPLATES[parsed.data.type]?.(null) ?? `## ${parsed.data.title ?? parsed.data.type}\n\nReport generated on ${new Date().toLocaleDateString()}.`;
  const title = parsed.data.title ?? `${parsed.data.type.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase())} — ${new Date().toLocaleDateString()}`;
  const [report] = await db.insert(reportsTable).values({ type: parsed.data.type, title, content }).returning();
  res.status(201).json(GetReportResponse.parse(toJson(report)));
});

router.get("/reports/:id", async (req, res): Promise<void> => {
  const params = GetReportParams.safeParse(req.params);
  if (!params.success) { res.status(400).json({ error: params.error.message }); return; }
  const [report] = await db.select().from(reportsTable).where(eq(reportsTable.id, params.data.id));
  if (!report) { res.status(404).json({ error: "Report not found" }); return; }
  res.json(GetReportResponse.parse(toJson(report)));
});

export default router;
